#!/usr/bin/env python3
"""Prepare two renders for the shared blind test.

Aligns B to A (sub-sample, with polarity check), matches B's integrated loudness
(ITU-R BS.1770) to A, trims both to the same length, and writes them as 24-bit FLAC
with neutral random names into audio/. Also writes config.js for index.html.

usage: python prep_audio.py REAL.wav NAM.wav [--label-a "Real amp"] [--label-b "NAM capture"]
needs: numpy scipy soundfile pyloudnorm
"""
import argparse, json, pathlib, secrets, base64
import numpy as np, soundfile as sf, pyloudnorm as pyln
from scipy.signal import fftconvolve

ROOT = pathlib.Path(__file__).resolve().parent.parent

ap = argparse.ArgumentParser()
ap.add_argument('a'); ap.add_argument('b')
ap.add_argument('--label-a', default='Real amp'); ap.add_argument('--label-b', default='NAM capture')
args = ap.parse_args()

A, sr = sf.read(args.a, always_2d=True, dtype='float64')
B, srb = sf.read(args.b, always_2d=True, dtype='float64')
assert sr == srb, f'sample rates differ: {sr} vs {srb}'
ch = min(A.shape[1], B.shape[1]); A, B = A[:, :ch], B[:, :ch]
n = min(len(A), len(B)); A, B = A[:n], B[:n]
mA, mB = A.mean(1), B.mean(1)

# loudest 10 s window of A for correlation
win, maxlag = int(10 * sr), int(0.1 * sr)
e = np.convolve(mA ** 2, np.ones(int(sr)), 'valid')[::int(sr)]
start = int(np.argmax(e[: max(1, (n - win - 2 * maxlag) // int(sr))])) * int(sr) + maxlag
seg_a = mA[start:start + win]
seg_b = mB[start - maxlag:start + win + maxlag]
xc = fftconvolve(seg_b, seg_a[::-1], 'valid')          # xc[k] ~ corr at lag k - maxlag
k = int(np.argmax(np.abs(xc))); pol = -1.0 if xc[k] < 0 else 1.0
y0, y1, y2 = pol * xc[k - 1], pol * xc[k], pol * xc[k + 1]
den = y0 - 2 * y1 + y2; frac = 0.5 * (y0 - y2) / den if den < 0 else 0.0
lag = (k - maxlag) + frac                                  # B(t + lag) lines up with A(t)

# fractional shift of B via FFT phase ramp: Bs[t] = B[t + lag]
N = 1 << int(np.ceil(np.log2(n + 2 * maxlag)))
f = np.fft.rfftfreq(N)
Bs = np.empty_like(B)
for c in range(ch):
    X = np.fft.rfft(B[:, c], N) * np.exp(2j * np.pi * f * lag)
    Bs[:, c] = pol * np.fft.irfft(X, N)[:n]
pad = int(np.ceil(abs(lag))) + 64                           # trim edges affected by the shift
A, Bs = A[pad:n - pad], Bs[pad:n - pad]

meter = pyln.Meter(sr)
la, lb = meter.integrated_loudness(A), meter.integrated_loudness(Bs)
g = 10 ** ((la - lb) / 20); Bs *= g
resid = Bs - A
esr = float((resid ** 2).sum() / (A ** 2).sum())
# raise BOTH by the same gain so the louder peak sits at -1 dBFS (fair, and playable on laptops/phones)
peak0 = max(np.abs(A).max(), np.abs(Bs).max())
common = 10 ** (-1 / 20) / peak0
A, Bs = A * common, Bs * common
peak = max(np.abs(A).max(), np.abs(Bs).max())

out = ROOT / 'audio'
for old in out.glob('*.flac'): old.unlink()
na, nb = f'take-{secrets.token_hex(3)}.flac', f'take-{secrets.token_hex(3)}.flac'
sf.write(out / na, A.astype(np.float32), sr, subtype='PCM_24', format='FLAC')
sf.write(out / nb, Bs.astype(np.float32), sr, subtype='PCM_24', format='FLAC')

# light obfuscation so the answer isn't readable at a glance in the page source
truth = base64.b64encode(json.dumps({na: 'A', nb: 'B'}).encode()).decode()[::-1]
files = [na, nb]; secrets.SystemRandom().shuffle(files)
cfg = (ROOT / 'config.js')
sheet, trials, clip_s, clips = '', 16, 8, '[]'
if cfg.exists():
    import re
    old = cfg.read_text()
    m = re.search(r'sheetUrl:\s*"([^"]*)"', old); sheet = m.group(1) if m else ''
    m = re.search(r'trials:\s*(\d+)', old); trials = int(m.group(1)) if m else 16
    m = re.search(r'clipSeconds:\s*([\d.]+)', old); clip_s = m.group(1) if m else 8
    m = re.search(r'\n[ \t]*clips:\s*([^\n]*?),?[ \t]*\n', old); clips = m.group(1) if m else '[]'
    if clips != '[]': print('note: kept your chosen clips; check them in lab.html if the new audio is a different performance')
cfg.write_text(f'''// Generated by tools/prep_audio.py. Paste your Google Apps Script web-app URL into sheetUrl.
window.BLIND_TEST = {{
  sheetUrl: "{sheet}",
  labels: {{ A: {json.dumps(args.label_a)}, B: {json.dumps(args.label_b)} }},
  files: {json.dumps(['audio/' + x for x in files])},
  key: "{truth}",
  trials: {trials},
  clipSeconds: {clip_s},
  clips: {clips},
  trimSeconds: {pad/sr:.6f},
  stats: {{ residualDb: {10*np.log10(esr):.1f}, esr: {esr:.2e}, gainDb: {20*np.log10(g):.2f}, alignSamples: {lag:.2f} }}
}};
''')
print(f'sr {sr}  ch {ch}  len {len(A)/sr:.1f}s')
print(f'alignment: B lag {lag:+.2f} samples, polarity {"inverted" if pol < 0 else "normal"}')
print(f'loudness: A {la:.2f} LUFS, B {lb:.2f} LUFS -> B gain {20*np.log10(g):+.2f} dB')
print(f'residual {10*np.log10(esr):.1f} dB rel A (ESR {esr:.2e})')
print(f'common gain on both {20*np.log10(common):+.1f} dB -> peak {20*np.log10(peak):.1f} dBFS, A now {meter.integrated_loudness(A):.1f} LUFS, B {meter.integrated_loudness(Bs):.1f} LUFS')
print('wrote', na, nb, 'and config.js')
